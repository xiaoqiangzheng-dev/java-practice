public class Example03 {
    public static void main(String[] args) {
        int i = 20;
        long l = i;
        float f = (float) l;
        double d = f;
        System.out.println("long类型变量l：" + l);
        System.out.println("float类型变量f：" + f);
        System.out.println("double类型变量d:" + d);
    }

}
